            f"On the straight sections its position part has mean "
            f"\\SI{{{fmt(1000*P['straight']['mean'],1)}}}{{\\milli\\metre}} and maximum "
            f"\\SI{{{fmt(1000*P['straight']['max'],1)}}}{{\\milli\\metre}}, and its angle part "
